#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*fromv;

	fromv = s;
	i = 0;
	while (i < n)
	{
		fromv[i] = (unsigned char)c;
		i++;
	}
	return (fromv);
}
/*
size_t는 메모리 크기나 배열 인덱스 등과 같은 비율을 표현하기 위해 특별히 설계된 데이터 타입입니다. size_t를 사용하는 이유는 다음과 같습니다:

목적에 맞는 타입: size_t는 메모리 크기와 같은 특정 용도에 맞게 정의된 타입입니다. 이 타입은 배열의 크기, 메모리 할당 크기 등을 나타내는 데 적합합니다.

플랫폼 독립성: size_t는 플랫폼에 따라 다르게 정의될 수 있습니다. 32비트 시스템에서는 32비트로, 64비트 시스템에서는 64비트로 정의되기 때문에, 다양한 플랫폼에서 메모리 크기를 안전하게 표현할 수 있습니다.

부호 없음: size_t는 부호가 없는 타입이므로 음수 값을 가질 수 없고, 이를 통해 메모리 크기를 안전하게 다룰 수 있습니다. 메모리 크기나 인덱스에 음수를 사용하는 것은 의미가 없기 때문에, 이를 명확하게 반영합니다.

표준 라이브러리와의 호환성: C와 C++의 표준 라이브러리에서 메모리 관련 함수들은 size_t를 사용하므로, 이 타입을 사용하면 코드의 일관성과 호환성을 유지할 수 있습니다.

이러한 이유들로 인해 size_t는 메모리 크기와 관련된 작업을 수행할 때 안전하고 효율적인 선택입니다.
*/